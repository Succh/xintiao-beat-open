// Remote end-to-end check: node test/e2e-remote.js wss://<host>/ws  (pair two simulated phones, 想你了, offline queue, poke)
const assert = require('assert'); const { Client } = require('./helpers')
const url = process.argv[2]
;(async () => {
  const a = new Client(url), b = new Client(url); await a.open(); await b.open()
  const wa = await a.req({ op: 'hello', name: '老板', device: 'Xiaomi Smart Band 9 Pro', mode: 'full' }, 'welcome', )
  const wb = await b.req({ op: 'hello', name: '宝贝', device: 'Redmi Watch 3', mode: 'notify' }, 'welcome')
  const pc = await a.req({ op: 'pair_code' }, 'pair_code'); console.log('pair code', pc.code)
  b.send({ op: 'pair_join', code: pc.code })
  const pa = await a.wait('paired', undefined, 8000), pb = await b.wait('paired', undefined, 8000)
  assert.equal(pa.partner.name, '宝贝'); assert.equal(pb.partner.name, '老板'); console.log('paired OK')
  const t0 = Date.now()
  a.send({ op: 'event', event: { kind: 'phrase', e: 'heart', text: '想你了', cid: 'e2e1' } })
  const ev = await b.wait('event', undefined, 8000); const s = await a.wait('sent', undefined, 8000)
  assert.equal(ev.event.text, '想你了'); assert.equal(ev.event.fromName, '老板'); assert.equal(s.delivered, true)
  console.log('想你了 delivered to B in', Date.now() - t0, 'ms; event:', JSON.stringify(ev.event))
  a.send({ op: 'event', event: { kind: 'miss', level: 'short', via: 'phone', cid: 'm1' } })
  const m = await b.wait('event', e => e.event.kind === 'miss', 8000); assert.equal(m.event.level, 'short')
  console.log('想你了 button (miss/short) A->B:', JSON.stringify(m.event))
  await b.close(); a.send({ op: 'event', event: { kind: 'miss', level: 'long', via: 'band', cid: 'q1' } })
  const q = await a.wait('sent', x => x.event.cid === 'q1', 8000); console.log('B offline -> delivered:', q.delivered)
  const b2 = new Client(url); await b2.open(); b2.send({ op: 'hello', uid: wb.uid, token: wb.token })
  const qq = await b2.wait('event', e => e.event.cid === 'q1', 8000); const dd = await a.wait('delivered', undefined, 8000); console.log('A got delivered receipt', dd.ids); console.log('queued miss/long delivered on reconnect:', qq.event.level)
  b2.send({ op: 'event', event: { kind: 'poke' } }); const p = await a.wait('event', undefined, 8000)
  console.log('poke B->A:', JSON.stringify(p.event))
  a.send({ op: 'unpair' }); await new Promise(r => setTimeout(r, 500))
  await a.close(); await b2.close(); console.log('E2E PASS')
})().catch(e => { console.error('E2E FAIL', e); process.exit(1) })
